/* ---------- Deterministic seeded shuffle (options only) ----------
   Authors always write the correct answer as options[0]. We shuffle
   once at load time using a seed derived from the question id, so the
   correct answer isn't always in the same position but the order is
   stable across page loads (same id -> same shuffle). */
function mulberry32(seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6D2B79F5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function seedFromId(id) {
  let h = 0;
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) | 0;
  return h;
}

export const QUESTION_BANK = RAW_QUESTIONS.map((q) => {
  const rng = mulberry32(seedFromId(q.id));
  const order = [0, 1, 2, 3];
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return {
    ...q,
    difficulty: LEVEL_ORDER[q.level] * 10 + q.diffIndex,
    options: order.map((i) => q.options[i]),
    correct: order.indexOf(0),
  };
});

